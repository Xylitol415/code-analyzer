import assert from "node:assert/strict";
import test from "node:test";
import { execFileSync } from "node:child_process";
import { mkdtemp, realpath, writeFile, rm } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { createApp } from "../src/server.js";
import { closeSession, getSession } from "../src/session-registry.js";
import { getMemoryService } from "../src/memory/service.js";

test("web flow publishes an answer, reuses it without a model call, restores IDs, and reports stale context", async t => {
  const root = await realpath(await mkdtemp(join(tmpdir(), "memory-e2e-")));
  const project = join(root, "project");
  execFileSync("git", ["init", "-q", project]);
  await writeFile(join(project, "feature.ts"), "export const enabled = true;\n");
  const git = (...args: string[]) => execFileSync("git", args, { cwd: project, stdio: "pipe" });
  git("add", "."); git("-c", "user.name=Fixture", "-c", "user.email=test@example.test", "-c", "commit.gpgsign=false", "commit", "-qm", "fixture");
  const previous = process.env.CODE_ANALYZER_DATA_DIR;
  process.env.CODE_ANALYZER_DATA_DIR = join(root, "data");
  const ids = new Set<string>();
  t.after(async () => { for (const id of ids) await closeSession(id); await getMemoryService()?.close(); previous === undefined ? delete process.env.CODE_ANALYZER_DATA_DIR : process.env.CODE_ANALYZER_DATA_DIR = previous; await rm(root, { recursive: true, force: true }); });
  const app = createApp("memory-token");
  const headers = { authorization: "Bearer memory-token", "content-type": "application/json" };
  const json = (path: string, body: unknown, method = "POST") => app.request(path, { method, headers, body: JSON.stringify(body) });
  assert.equal((await app.request(`/memory/knowledge?project=${encodeURIComponent(project)}`)).status, 401);
  const model = { baseUrl: "https://never.invalid/v1", model: "fixture" };
  const open = async (historyId?: string) => { const response = await json("/sessions", { project, llm: model, ...(historyId ? { historyId } : {}) }); assert.equal(response.status, 200); const result = await response.json(); ids.add(result.id); return result; };
  const first = await open();
  let generated = 0;
  const s = getSession(first.id)!.session;
  t.mock.method(s, "prompt", async question => {
    generated++;
    s.sessionManager.appendMessage({ role: "user", content: question, timestamp: Date.now() });
    s.sessionManager.appendMessage({ role: "assistant", content: [{ type: "text", text: "默认启用，见 feature.ts:1。" }], api: "openai-completions", provider: "custom-openai", model: "fixture", timestamp: Date.now(), stopReason: "stop", usage: { input: 0, output: 0, cacheRead: 0, cacheWrite: 0, totalTokens: 0, cost: { input: 0, output: 0, cacheRead: 0, cacheWrite: 0, total: 0 } } });
    s.refreshContext();
  });
  const answerResponse = await json(`/sessions/${first.id}/ask?stream=false`, { question: "是否默认启用？", requestId: "first" });
  assert.equal(answerResponse.status, 200, await answerResponse.clone().text());
  const answer = await answerResponse.json();
  assert.ok(answer.answerId, "completed API answer must expose its stable backend ID");
  const candidateResponse = await json("/memory/knowledge", { answerId: answer.answerId });
  assert.equal(candidateResponse.status, 200, await candidateResponse.clone().text());
  const candidate = await candidateResponse.json();
  const published = await json(`/memory/knowledge/${candidate.id}/review`, { action: "publish", expectedRevision: candidate.revision, conditions: "仅本次提交静态代码", evidence: [{ path: "feature.ts", startLine: 1, endLine: 1 }] });
  assert.equal(published.status, 200, await published.clone().text());
  const second = await open();
  t.mock.method(getSession(second.id)!.session, "prompt", async () => { throw new Error("exact reuse must not call model"); });
  const reusedResponse = await json(`/sessions/${second.id}/ask?stream=false`, { question: "是否默认启用？", requestId: "exact" });
  assert.equal(reusedResponse.status, 200, await reusedResponse.clone().text());
  const reused = await reusedResponse.json();
  assert.equal(reused.source, "exact"); assert.equal(reused.usage.quality, "no-model-call"); assert.equal(generated, 1);
  const replay = await json(`/sessions/${second.id}/ask`, { question: "是否默认启用？", requestId: "exact" });
  assert.match(await replay.text(), /event: done[\s\S]*"answerId"/);
  await closeSession(second.id);
  const restored = await open(second.historyId);
  assert.equal(restored.messages.at(-1).answerId, reused.answerId);
  await writeFile(join(project, "feature.ts"), "export const enabled = false;\n");
  const stale = await json(`/sessions/${restored.id}/ask?stream=false`, { question: "现在呢？" });
  assert.equal(stale.status, 409); assert.equal((await stale.json()).code, "context_stale");
});
